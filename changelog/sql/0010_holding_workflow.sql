        assignment_detached_at_utc, created_at_utc, updated_at_utc, version)
    SELECT DISTINCT ON (i.group_id, COALESCE(i.context ->> 'cph', ''))
           i.group_id,
           COALESCE(i.context ->> 'cph', ''),
           NULLIF(BTRIM(i.assigned_to), ''),
